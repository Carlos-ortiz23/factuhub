"""Password hashing and session-token minting.

Two different secrets are handled here, and the difference between them matters:

- A **password** is chosen by a human, so it is low-entropy and guessable. It is
  stored with Argon2id, whose slowness is the whole point.
- A **session token** is 256 random bits generated by the server. Guessing it is
  not a realistic attack, so it is stored as a plain SHA-256 digest: the point is
  only that the raw token must never be readable from the database.

Hashing a session token with Argon2 would be actively harmful — a fast hash is
correct here precisely because the input is already unguessable, and a slow hash
on every authenticated request would hand an attacker a cheap denial of service.
"""

from __future__ import annotations

import hashlib
import secrets
from base64 import urlsafe_b64encode

from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError, VerifyMismatchError

#: Minimum length, not complexity rules. Length is what actually resists
#: guessing, and composition rules (one uppercase, one symbol) mostly produce
#: `Password1!`. Assumption, not a specification requirement: §11.1 asks for
#: secure authentication and does not state a policy.
PASSWORD_MIN_LENGTH = 12

#: Upper bound so that hashing cannot be weaponised into a denial of service.
PASSWORD_MAX_LENGTH = 128

#: 32 bytes = 256 bits of entropy for a session token.
SESSION_TOKEN_BYTES = 32

#: base64url of 32 bytes, without padding.
SESSION_TOKEN_LENGTH = 43

#: Argon2id defaults from argon2-cffi (RFC 9106 recommended profile). Named so
#: the chosen cost is visible in one place and can be raised later.
_password_hasher = PasswordHasher()


class PasswordPolicyError(ValueError):
    """The candidate password does not satisfy the policy."""


def _check_password_policy(password: str) -> None:
    if len(password) < PASSWORD_MIN_LENGTH:
        raise PasswordPolicyError(
            f"Password must be at least {PASSWORD_MIN_LENGTH} characters long."
        )
    if len(password) > PASSWORD_MAX_LENGTH:
        raise PasswordPolicyError(
            f"Password must be at most {PASSWORD_MAX_LENGTH} characters long."
        )


def hash_password(password: str) -> str:
    """Return an Argon2id hash of `password`.

    Raises `PasswordPolicyError` if the password does not satisfy the policy.
    """
    _check_password_policy(password)
    return _password_hasher.hash(password)


def verify_password(password: str, password_hash: str) -> bool:
    """Return whether `password` matches the stored hash.

    Never raises for a bad candidate or a damaged stored hash: a corrupted row
    must produce a failed login, not a server error that distinguishes itself
    from a wrong password.
    """
    try:
        return _password_hasher.verify(password_hash, password)
    except (VerifyMismatchError, VerificationError, InvalidHashError):
        return False


def generate_session_token() -> str:
    """Return a new URL-safe session token.

    URL-safe because the token travels in a cookie and, when a client needs it,
    in a query string that must not require escaping.
    """
    return urlsafe_b64encode(secrets.token_bytes(SESSION_TOKEN_BYTES)).decode("ascii").rstrip("=")


def hash_session_token(token: str) -> str:
    """Return the hex SHA-256 digest used to look a session up.

    The database stores this digest, never the token, so a leaked backup does not
    hand out live sessions.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()
